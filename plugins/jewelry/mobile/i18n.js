  var LANG_KEYS = ["zh", "zhHant", "en", "it", "ja", "ko"];
  var LANG_LABELS = { zh: "简体中文", zhHant: "繁體中文", en: "English", it: "Italiano", ja: "日本語", ko: "한국어" };

  function detectLang() {
    try {
      var saved = localStorage.getItem("yz_m_lang");
      if (saved && I18N[saved]) return saved;
    } catch (e) {}
    var nav = (navigator.language || "zh").toLowerCase();
    if (nav.indexOf("zh") === 0) {
      if (nav.indexOf("tw") >= 0 || nav.indexOf("hk") >= 0 || nav.indexOf("hant") >= 0) return "zhHant";
      return "zh";
    }
    if (nav.indexOf("ja") === 0) return "ja";
    if (nav.indexOf("ko") === 0) return "ko";
    if (nav.indexOf("it") === 0) return "it";
    if (nav.indexOf("en") === 0) return "en";
    return "zh";
  }

  var current = detectLang();

  window.I18N = I18N;
  window.LANG_KEYS = LANG_KEYS;
  window.LANG_LABELS = LANG_LABELS;
  window.YZLang = {
    get: function () { return current; },
    set: function (l) {
      if (!I18N[l]) l = "zh";
      current = l;
      try { localStorage.setItem("yz_m_lang", l); } catch (e) {}
    }
  };

  window.t = function (key, params) {
    var dict = I18N[current] || I18N.zh;
    var val = dict[key];
    if (val === undefined) val = I18N.zh[key];
    if (val === undefined) return key;
    if (params) {
      for (var k in params) {
        if (Object.prototype.hasOwnProperty.call(params, k)) {
          val = val.split("{" + k + "}").join(params[k]);
        }
      }
    }
    return val;
  };
